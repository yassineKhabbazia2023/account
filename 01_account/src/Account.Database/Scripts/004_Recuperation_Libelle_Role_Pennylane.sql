-- Insérer ou mettre à jour les rôles
MERGE [account].[Role] AS target
USING (
    SELECT DISTINCT AccountId, ContactId
    FROM #TempSubscriptionFunctions
) AS source
ON target.AccountId = source.AccountId AND target.ContactId = source.ContactId
WHEN NOT MATCHED THEN
    INSERT (AccountId, ContactId, IsCustomerRelation, ActionLevel)
    VALUES (source.AccountId, source.ContactId, 0, 3);

-- UPDATE : si IsCustomerRelation = 1 et ActionLevel < 4
UPDATE r
SET r.ActionLevel = 4
FROM [account].[Role] r
JOIN #TempSubscriptionFunctions tsf ON r.AccountId = tsf.AccountId AND r.ContactId = tsf.ContactId
WHERE r.IsCustomerRelation = 1 AND r.ActionLevel <> 4;

-- UPDATE conditionnel sur IsCustomerRelation NULL
UPDATE r
SET 
    r.IsCustomerRelation = 0,
    r.ActionLevel = 3
FROM [account].[Role] r
JOIN #TempSubscriptionFunctions tsf 
    ON r.AccountId = tsf.AccountId AND r.ContactId = tsf.ContactId
WHERE r.IsCustomerRelation IS NULL;

-- Mapping FunctionName → LabelId
WITH FunctionLabelMapping AS (
    SELECT 'Expert comptable' AS FunctionName, 4 AS LabelId
    UNION ALL
    SELECT 'Collaborateur principal', 5
    UNION ALL
    SELECT 'Chef de mission', 3
),
-- RôleLabel existants
ExistingRoleLabels AS (
    SELECT rl.AccountId, rl.ContactId, rl.LabelId
    FROM [account].[RoleLabel] rl
),
-- Données à traiter
ToProcess AS (
    SELECT tsf.AccountId, tsf.ContactId, tsf.FunctionName, flm.LabelId
    FROM #TempSubscriptionFunctions tsf
    JOIN FunctionLabelMapping flm ON tsf.FunctionName = flm.FunctionName
)

-- Ajouter les RoleLabels manquants
INSERT INTO [account].[RoleLabel] (AccountId, ContactId, LabelId, CreatedDate, CreatedBy)
SELECT tp.AccountId, tp.ContactId, tp.LabelId, GETUTCDATE(), tp.ContactId
FROM ToProcess tp
LEFT JOIN ExistingRoleLabels erl 
    ON tp.AccountId = erl.AccountId AND tp.ContactId = erl.ContactId AND tp.LabelId = erl.LabelId
WHERE erl.LabelId IS NULL;